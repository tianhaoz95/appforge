import 'package:flutter/material.dart';
import 'package:flutter_markdown_plus/flutter_markdown_plus.dart';

enum LegalNoticeType {
  privacyNotice,
  userAgreement,
}

class LegalNoticeScreen extends StatelessWidget {
  final LegalNoticeType type;

  const LegalNoticeScreen({
    super.key,
    required this.type,
  });

  String _getTitle() {
    switch (type) {
      case LegalNoticeType.privacyNotice:
        return 'Privacy Notice';
      case LegalNoticeType.userAgreement:
        return 'User Agreement';
    }
  }

  String _getContent() {
    switch (type) {
      case LegalNoticeType.privacyNotice:
        return '''
# Privacy Notice for MicroForge

**Last Updated: March 18, 2026**

Welcome to MicroForge. We are committed to protecting your privacy and providing a transparent experience when you use our platform to "forge" micro-apps.

## 1. Information We Collect

### 1.1 Account Information
When you create an account, we collect your email address and display name via Firebase Authentication. This is necessary to manage your access and identify your forged apps.

### 1.2 User-Generated Content
We store your conversations with the MicroForge AI and the code for the micro-apps you forge in Cloud Firestore. This allows you to access your history and apps across different sessions.

### 1.3 Device Information
Micro-apps you forge may request access to device features such as:
- **Geolocation:** To provide location-aware functionality.
- **Accelerometer:** To enable motion and tilt-based interactions.
- **Notifications:** To keep you informed of background tasks.

Access to these features is strictly controlled by your device's permission system and the settings within the MicroForge app.

## 2. How We Use Your Information

### 2.1 Service Provisioning
We use your data to provide the core functionality of MicroForge, including:
- Generating micro-apps using the Gemini AI (via Firebase AI Logic).
- Storing and retrieving your micro-apps and conversation history.
- Executing background tasks for your forged apps.

### 2.2 AI Generation
Your prompts and existing app context are sent to the Gemini API (Google AI) to generate and enhance micro-apps. This data is handled according to Google's generative AI privacy policies.

## 3. Data Sharing
We do not sell your personal data. We share information only with service providers (like Google/Firebase) necessary to operate the platform or as required by law.

## 4. Your Control and Rights
- **Access and Portability:** You can view your forged apps and history at any time.
- **Correction:** You can update your display name in the Settings screen.
- **Deletion:** You can delete your account and all associated data (conversations, forged apps, profile) permanently from the Settings screen.

## 5. Security
We use industry-standard security measures provided by Firebase to protect your data. However, no method of transmission or storage is 100% secure.

## 6. Contact Us
If you have any questions about this Privacy Notice, please contact us through the feedback mechanism in the app.
''';
      case LegalNoticeType.userAgreement:
        return '''
